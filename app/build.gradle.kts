// Release signing comes from an untracked keystore.properties at the project root:
//   storeFile=keystore/upload.jks, storePassword=..., keyAlias=upload, keyPassword=...
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.esmer.queenfinder"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.esmer.queenfinder"
        minSdk = 29
        targetSdk = 37
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 shrinking and resource removal; keep rules live in src/main/keepRules.
            optimization {
                enable = true
            }
            if (keystoreProps.isNotEmpty()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    bundle {
        // One bundle serves every ABI and density; Play delivers only what each device needs.
        abi { enableSplit = true }
        density { enableSplit = true }
        language { enableSplit = true }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
    androidResources {
        // Keep the model uncompressed so it can be memory-mapped by the interpreter.
        noCompress += listOf("tflite")
    }
}

